#!/usr/bin/env python3
"""Create the STREAMLITWEB service user and its RSA key pair.

Layer 2 of the three-layer auth model: the single Snowflake identity the
Streamlit app authenticates as. Everything the app can do in Snowflake is
whatever STREAMLITWEB_ROLE has been granted by sql/08_grants.sql.

Generates:
  keys/streamlitweb_key.p8    PKCS#8 RSA private key (mode 600)
  keys/streamlitweb_key.pub   matching PEM public key
  .env.service                credentials for the app / server (mode 600)

Key-pair rather than password: a user with no password cannot be challenged
for MFA, and cannot sign in interactively at all.

Idempotent: reuses an existing key unless --force, and re-syncs the public key
onto the user either way.

Usage:
    python scripts/create_service_user.py [--force]
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))

from dotenv import load_dotenv  # noqa: E402

from credentials import load_or_create_key_pair  # noqa: E402
from sf import FALLBACK_WAREHOUSE, connect  # noqa: E402

USER = "STREAMLITWEB"
ROLE = "STREAMLITWEB_ROLE"
KEY_PATH = ROOT / "keys" / "streamlitweb_key.p8"
SERVICE_ENV = ROOT / ".env.service"
STATEMENT_TIMEOUT = 60


def write_service_env() -> list[str]:
    """Write the app-side env file, derived from the admin .env."""
    load_dotenv(ROOT / ".env", override=True)
    values = {
        "SNOWFLAKE_ACCOUNT": os.environ["SNOWFLAKE_ACCOUNT"],
        "SNOWFLAKE_USER": USER,
        "SNOWFLAKE_ROLE": ROLE,
        "SNOWFLAKE_WAREHOUSE": os.getenv("SNOWFLAKE_WAREHOUSE", FALLBACK_WAREHOUSE),
        "SNOWFLAKE_DATABASE": os.getenv("SNOWFLAKE_DATABASE", "CUAD_DB"),
        "SNOWFLAKE_SCHEMA": os.getenv("SNOWFLAKE_SCHEMA", "CORPUS"),
        "SNOWFLAKE_AUTHENTICATOR": "SNOWFLAKE_JWT",
        "SNOWFLAKE_PRIVATE_KEY_PATH": f"./keys/{KEY_PATH.name}",
        "PRIVATE_KEY_PASSPHRASE": "",
    }
    lines = [
        "# Streamlit service identity (layer 2 of 3). Generated by",
        "# `make service-user`. Do not edit by hand; do not commit.",
        "",
    ]
    lines += [f"{key}={value}" for key, value in values.items()]
    SERVICE_ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    SERVICE_ENV.chmod(0o600)
    return list(values)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="rotate the key pair")
    args = ap.parse_args()

    existed = KEY_PATH.exists()
    public_key = load_or_create_key_pair(KEY_PATH, force=args.force)
    print(f"{'reused' if existed and not args.force else 'generated'} {KEY_PATH.relative_to(ROOT)}")

    with connect(database="CUAD_DB", schema="CORPUS") as conn:
        cur = conn.cursor()

        cur.execute(
            f"""
            CREATE USER IF NOT EXISTS {USER}
              DEFAULT_ROLE = {ROLE}
              DEFAULT_WAREHOUSE = {FALLBACK_WAREHOUSE}
              RSA_PUBLIC_KEY = '{public_key}'
              COMMENT = 'Streamlit app service identity (layer 2 of 3)'
            """
        )
        # Re-sync every run, so a rotated key takes effect and a first run on an
        # existing user still lands the right settings.
        cur.execute(
            f"""
            ALTER USER {USER} SET
              DEFAULT_ROLE = {ROLE},
              DEFAULT_WAREHOUSE = {FALLBACK_WAREHOUSE},
              RSA_PUBLIC_KEY = '{public_key}',
              STATEMENT_TIMEOUT_IN_SECONDS = {STATEMENT_TIMEOUT},
              COMMENT = 'Streamlit app service identity (layer 2 of 3)'
            """
        )
        cur.execute(f"GRANT ROLE {ROLE} TO USER {USER}")

        cur.execute("SELECT CURRENT_ROLE()")
        (current_role,) = cur.fetchone()
        cur.execute(f"SHOW ROLES LIKE '{ROLE}'")
        role_exists = bool(cur.fetchall())

    keys = write_service_env()

    print(f"\nservice identity ready")
    print(f"  user            {USER}")
    print(f"  default role    {ROLE} (exists: {bool(role_exists)})")
    print(f"  provisioned by  {current_role}")
    print(f"  key             keys/{KEY_PATH.name} (mode 600)")
    print(f"  app env         {SERVICE_ENV.name} (mode 600, gitignored)")
    print(f"  statement cap   {STATEMENT_TIMEOUT}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
