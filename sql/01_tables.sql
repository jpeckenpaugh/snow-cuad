-- Step 2b: tables, file format, internal stage.
-- Run with: make setup

USE WAREHOUSE CUAD_WH;
USE DATABASE CUAD_DB;
USE SCHEMA CORPUS;

-- Load files are NDJSON; newlines inside contract text survive intact.
CREATE OR REPLACE FILE FORMAT CUAD_JSON
  TYPE = JSON
  COMPRESSION = AUTO
  COMMENT = 'NDJSON load files';

CREATE OR REPLACE STAGE CUAD_LOAD
  FILE_FORMAT = CUAD_JSON
  COMMENT = 'Load files only; emptied by `make clean-stage`';

CREATE OR REPLACE TABLE CONTRACTS (
  DOC_ID    STRING NOT NULL,
  TITLE     STRING NOT NULL,
  CHAR_LEN  NUMBER NOT NULL,
  CONSTRAINT PK_CONTRACTS PRIMARY KEY (DOC_ID)
);

CREATE OR REPLACE TABLE CONTRACT_TEXT (
  DOC_ID     STRING NOT NULL,
  FULL_TEXT  STRING NOT NULL,
  CONSTRAINT PK_CONTRACT_TEXT PRIMARY KEY (DOC_ID)
);

CREATE OR REPLACE TABLE CLAUSES (
  CLAUSE_ID    STRING NOT NULL,
  DOC_ID       STRING NOT NULL,
  CATEGORY     STRING NOT NULL,
  QUESTION     STRING NOT NULL,
  ANSWER_TEXT  STRING NOT NULL,
  ANSWER_START NUMBER NOT NULL,
  ANSWER_END   NUMBER NOT NULL,
  CONSTRAINT PK_CLAUSES PRIMARY KEY (CLAUSE_ID)
);

CREATE OR REPLACE TABLE CLAUSE_CATEGORIES (
  CATEGORY       STRING NOT NULL,
  DESCRIPTION    STRING NOT NULL,
  ANSWER_FORMAT  STRING NOT NULL,
  GRP            STRING NOT NULL,
  CONSTRAINT PK_CLAUSE_CATEGORIES PRIMARY KEY (CATEGORY)
);
