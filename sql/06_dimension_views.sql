-- Step 3c: browse views over the derived dimensions.
-- Run with: make views

USE WAREHOUSE CUAD_WH;
USE DATABASE CUAD_DB;
USE SCHEMA CORPUS;

-- One row per contract: everything the register table needs.
CREATE OR REPLACE VIEW V_CONTRACT_BROWSE AS
SELECT
  c.DOC_ID,
  c.TITLE,
  c.CHAR_LEN,
  d.DOC_TYPE,
  d.AGREEMENT_YEAR,
  d.JURISDICTION,
  d.CLAUSE_COUNT,
  (
    SELECT LISTAGG(p.PARTY_NAME, ' · ')
    FROM CONTRACT_PARTY p
    WHERE p.DOC_ID = c.DOC_ID
  ) AS PARTIES
FROM CONTRACTS c
JOIN CONTRACT_DIM d
  ON d.DOC_ID = c.DOC_ID;

-- Facet value lists with counts, including the explicit unknown buckets.
CREATE OR REPLACE VIEW V_FACET_TYPE AS
SELECT DOC_TYPE, COUNT(*) AS DOC_COUNT
FROM CONTRACT_DIM
GROUP BY DOC_TYPE;

CREATE OR REPLACE VIEW V_FACET_YEAR AS
SELECT AGREEMENT_YEAR, COUNT(*) AS DOC_COUNT
FROM CONTRACT_DIM
GROUP BY AGREEMENT_YEAR;

CREATE OR REPLACE VIEW V_FACET_JURISDICTION AS
SELECT JURISDICTION, COUNT(*) AS DOC_COUNT
FROM CONTRACT_DIM
GROUP BY JURISDICTION;

CREATE OR REPLACE VIEW V_FACET_PARTY AS
SELECT PARTY_NAME, COUNT(DISTINCT DOC_ID) AS DOC_COUNT
FROM CONTRACT_PARTY
GROUP BY PARTY_NAME;

-- The clause index: distinct documents per category, most common first.
CREATE OR REPLACE VIEW V_CATEGORY_INDEX AS
SELECT
  s.CATEGORY,
  cc.DESCRIPTION,
  cc.GRP,
  s.DOC_COUNT,
  s.SPAN_COUNT
FROM CATEGORY_STATS s
JOIN CLAUSE_CATEGORIES cc
  ON cc.CATEGORY = s.CATEGORY;

-- Related documents, already joined to the target contract's identity.
CREATE OR REPLACE VIEW V_RELATED_DOC AS
SELECT
  r.DOC_ID,
  r.RELATED_DOC_ID,
  r.RANK,
  r.SCORE,
  r.REASONS,
  c.TITLE AS RELATED_TITLE,
  d.DOC_TYPE AS RELATED_TYPE,
  d.AGREEMENT_YEAR AS RELATED_YEAR
FROM RELATED_DOC r
JOIN CONTRACTS c
  ON c.DOC_ID = r.RELATED_DOC_ID
JOIN CONTRACT_DIM d
  ON d.DOC_ID = r.RELATED_DOC_ID;
